import assert from 'node:assert/strict';
import './runtime-stub.mjs';
import {DEFAULT_STATIONS} from '../module/radio/stations.mjs';
import {validateStations} from '../module/radio/core.mjs';
import {stations,repairRadioPresets,migrateRadioPresets,radioMarkup,radioView} from '../module/radio/radio.mjs';
const NS='the-smoke';
const ids=DEFAULT_STATIONS.map(s=>s.id);
assert.equal(ids.length,6,'only six supported station presets');
assert.ok(DEFAULT_STATIONS.every(s=>s.stream?.startsWith('https://')),'default radio stations have native feeds');
assert.ok(!ids.includes('codesouth')&&!ids.includes('esencia-urbana'),'no dead broadcaster entries in default dial');
assert.equal(validateStations(DEFAULT_STATIONS).length,6,'all station URLs remain valid');
const bad='https://codesouth.out.airtime.pro/codesouth_a';
const legacy=[...DEFAULT_STATIONS,{id:'codesouth',name:'CodeSouth.FM',genre:'garage',stream:bad,website:'https://www.codesouth.fm/'},{id:'esencia-urbana',name:'Esencia Urbana',genre:'reggae',stream:'',website:'https://www.esenciaurbana.net/'}];
const repaired=repairRadioPresets(legacy);
assert.equal(repaired.length,6,'legacy nonfunctional stations removed from old worlds');
assert.deepEqual(repaired.map(x=>x.id),ids);
const custom={...legacy[6],stream:'https://example.com/verified-by-gm.mp3'};
assert.equal(repairRadioPresets([...DEFAULT_STATIONS,custom]).length,6,'retired broadcasters remain removed even with an old custom stream');
await game.settings.set(NS,'radioStations',JSON.stringify(legacy));
await game.settings.set(NS,'radioPresetVersion',513);
assert.deepEqual(stations().map(x=>x.id),ids,'client sees station repair before migration');
assert.equal(await migrateRadioPresets(),true);
assert.equal(game.settings.get(NS,'radioPresetVersion'),515);
assert.equal(JSON.parse(game.settings.get(NS,'radioStations')).length,6);
assert.equal(await migrateRadioPresets(),false,'migration is idempotent');
await game.settings.set(NS,'radioStations',JSON.stringify([...DEFAULT_STATIONS,custom]));
assert.equal(stations().length,6,'retired broadcasters stay removed from pre-existing customised settings');
await game.settings.set(NS,'radioStations','');
globalThis.canvas={scene:null,tokens:{controlled:[]}};
const actor={id:'pc1',name:'PC',type:'character',isOwner:true};
game.user.character=actor;game.actors=Object.assign([actor],{get:id=>id===actor.id?actor:null});
await game.settings.set(NS,'radioEnabled',true);
assert.ok(radioView(actor).station?.stream,'default station is a native playable stream');
assert.match(radioMarkup(actor),/data-radio-volume/,'native volume works for default stations');
console.log('radio presets: six direct stations, dead presets removed, upgrade preserves user feeds, volume and control remain intact — ok');
