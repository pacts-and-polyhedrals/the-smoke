import assert from 'node:assert/strict';
import {NS,scene,makeCombat,vt,jt,ut,jaz,settings} from './chase-harness.mjs';
import {installChase} from '../module/world/chase.mjs';
import '../module/combat/combat.mjs';
import {stateOf,pendingResponses} from '../module/world/chase-state.mjs';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
settings.chaseDelay=0;settings.chaseMode='full';
const c=makeCombat();const [cop,pc]=await c.createEmbeddedDocuments('Combatant',[{tokenId:ut.id,sceneId:scene.id,actorId:ut.actor.id},{tokenId:jt.id,sceneId:scene.id,actorId:jaz.id}]);
await c.setFlag(NS,'chase',{mode:'full',auto:true,since:Date.now(),lastSeen:{[jaz.id]:{at:Date.now(),point:[vt.x+100,vt.y+150]}}});
await c.update({[`flags.${NS}.state`]:{phase:'resolve',round:1,cursor:0,queue:[{cid:cop.id,kind:'action',value:6,die:0},{cid:pc.id,kind:'action',value:4,die:0}]}});
const id='blockingYellow';await vt.update({[`flags.${NS}.prompts.${id}`]:{kind:'driveCheck',status:'review',result:{outcomeKey:'fullSuccess'},context:{key:`${c.id}:1:0`}}});
assert.equal(pendingResponses(c).length,1);
installChase();Hooks.callAll('updateCombat',c,{});
await sleep(240);
assert.equal(stateOf(c).cursor,0,'Full Auto must not proceed while player driving result awaits review');
assert.ok(!c.getFlag(NS,'chase')?.action,'No NPC action should execute while a real response blocks');
await vt.update({[`flags.${NS}.prompts.-=${id}`]:null});
Hooks.callAll('updateCombat',c,{});
const end=Date.now()+7000;
while(Date.now()<end && stateOf(c).cursor===0)await sleep(30);
assert.equal(stateOf(c).cursor,1,'On real resolution, police executes and then advances exactly to player turn');
console.log('full auto blocked: genuine saved-player prompt prevents all NPC progress until cleared; next player die is not skipped — ok');
process.exit(0);
